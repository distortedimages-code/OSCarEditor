#!/usr/bin/env python3
"""Regenerate Source/core/FactoryBank.h from the codemechanic oscar-sysex-grammar repo.

usage: python3 tools/make_factory_bank.py <path to oscar-sysex-grammar>
Only the voice block is used: the waveform block of that archive is damaged
(every 0x0A was expanded to 0x0D 0x0A by a text-mode copy).
"""
import os
import sys

repo = sys.argv[1]
d = open(os.path.join(repo, "sysex/factory/FactoryPatch_Wavetable.syx"), "rb").read()
i = d.index(bytes([0xF0, 0x2B, 0x02]))
j = d.index(0xF7, i)
v = d[i + 3:j]
assert len(v) == 2304 and max(v) <= 0x0F

names = {}
for line in open(os.path.join(repo, "sysex/factory/FactoryPatchNames.txt")):
    line = line.strip()
    if line:
        n, name = line.split("\t", 1)
        names[int(n)] = name.strip()

order = [-k for k in range(1, 13)] + list(range(1, 25))  # wire order: -1..-12, 1..24
out = ["// Generated by tools/make_factory_bank.py from codemechanic/oscar-sysex-grammar (MIT).",
       "// Voice block only: the waveform block of that archive is damaged (CR/LF).",
       "#pragma once", "#include <cstdint>", "namespace oscar::factory {",
       "static const std::uint8_t kVoiceBank[2304] = {"]
for k in range(0, 2304, 32):
    out.append("    " + ", ".join(f"0x{b:02X}" for b in v[k:k + 32]) + ",")
out += ["};", "static const char* const kVoiceNames[36] = {",
        "    " + ", ".join('"%s"' % names[n] for n in order), "};",
        "} // namespace oscar::factory"]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "..", "Source/core/FactoryBank.h"), "w").write("\n".join(out) + "\n")
